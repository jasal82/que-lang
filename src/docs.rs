/// Built-in function metadata for completions and hover documentation.

/// Information about a built-in function or keyword.
#[derive(Debug, Clone)]
pub struct BuiltinInfo {
    pub name: &'static str,
    pub signature: &'static str,
    pub documentation: &'static str,
    pub kind: BuiltinKind,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum BuiltinKind {
    Function,
    Keyword,
    Type,
    Constant,
    /// An object exposing methods, e.g. `env`.
    Namespace,
}

/// All Que keywords.
///
/// Reserved words only — what `TokenKind::keyword` recognises. Names that read
/// like keywords but are not (`env` and `secret` are builtins, `compose` is a
/// builtin, `pipe` is the `|>` operator, `deps`/`inputs`/`outputs` are
/// task attribute names) are completed and documented through
/// `builtin_functions` and `keyword_doc` instead.
pub const KEYWORDS: &[&str] = &[
    "let", "mut", "fn", "task", "type", "enum", "struct",
    "impl", "trait",
    "if", "else", "match", "for", "in", "while", "loop",
    "return", "break", "continue",
    "import", "as", "from", "pub",
    "true", "false", "null",
    "try", "catch", "finally", "defer",
    "spawn", "parallel",
    "where", "with",
];

